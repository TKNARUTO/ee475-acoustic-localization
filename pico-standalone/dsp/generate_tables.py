"""Reproduce the existing HF2 Gap spectrum and portable float FFT constants.

No source-module import, audio export, calibration write or hardware access.
The embedded PCM hash must match the existing phone WAV's interior period.
"""
from pathlib import Path
import hashlib
import numpy as np

N = 4096
FS = 48000
EXPECTED_PCM_SHA256 = '87731c4edad62174a04c507f843c1a331785f9b8289517f7162d161cee85eadd'

def floats(name, values):
    values = np.asarray(values, dtype=np.float32)
    encoded = [float(value).hex() + 'f' for value in values]
    rows = [', '.join(encoded[i:i+4]) for i in range(0, len(encoded), 4)]
    return 'static const float ' + name + '[' + str(len(values)) + '] = {\n    ' + ',\n    '.join(rows) + '\n};\n'

def main():
    frequencies = np.fft.rfftfreq(N, 1 / FS)
    indices = np.flatnonzero((frequencies >= 18000) & (frequencies <= 22000))
    rng = np.random.default_rng(0xEE4750A9)
    spectrum = np.zeros(N // 2 + 1, dtype=np.complex128)
    taper = np.minimum(1, np.minimum((frequencies[indices] - 18000 + 12) / 100,
                                    (22000 - frequencies[indices] + 12) / 100))
    spectrum[indices] = taper * np.exp(1j * rng.uniform(-np.pi, np.pi, len(indices)))
    burst = np.fft.irfft(spectrum, N)
    window = np.zeros(N)
    window[:2048] = 1
    ramp = .5 - .5 * np.cos(np.linspace(0, np.pi, 64))
    window[:64] *= ramp
    window[2048-64:2048] *= ramp[::-1]
    samples = burst * window
    samples *= .35 / max(np.max(np.abs(samples)), 1e-12)
    pcm_hash = hashlib.sha256(np.rint(samples * 32767).astype('<i2').tobytes()).hexdigest()
    if pcm_hash != EXPECTED_PCM_SHA256:
        raise RuntimeError('HF2 Gap template mismatch: ' + pcm_hash)
    reference = np.fft.rfft(samples)[indices]
    quarter_sine = np.sin(2 * np.pi * np.arange(N // 4 + 1) / N)
    # Endpoints are mathematical constants, not platform libm residue.
    quarter_sine[0] = 0
    quarter_sine[-1] = 1
    text = ('/* Generated by generate_tables.py; existing HF2 Gap code unchanged.\n'
            ' * PCM16LE SHA256: ' + pcm_hash + '\n */\n'
            '#ifndef EE475_GAP_TABLES_H\n#define EE475_GAP_TABLES_H\n'
            'enum { GAP_FIRST_BIN = 1536, GAP_BAND_BINS = 342 };\n')
    text += floats('gap_reference_real', reference.real)
    text += floats('gap_reference_imag', reference.imag)
    text += floats('gap_quarter_sine', quarter_sine)
    text += '#endif\n'
    destination = Path(__file__).with_name('gap_tables.h')
    destination.write_text(text, encoding='ascii')
    q15 = np.rint(quarter_sine * 32768).astype(np.int32)
    integer_rows = [', '.join(str(int(v)) for v in q15[i:i+12]) for i in range(0, len(q15), 12)]
    integer_text = ('/* Generated by generate_tables.py. +32768 is intentional. */\n'
                    '#ifndef EE475_GAP_INTEGER_TABLES_H\n#define EE475_GAP_INTEGER_TABLES_H\n'
                    '#include <stdint.h>\nstatic const int32_t gap_q15_quarter_sine[1025] = {\n    '
                    + ',\n    '.join(integer_rows) + '\n};\n#endif\n')
    integer_destination = destination.with_name('gap_integer_tables.h')
    integer_destination.write_text(integer_text, encoding='ascii')
    print('Template PCM SHA256:', pcm_hash)
    print('Constant table bytes:', (2 * len(indices) + len(quarter_sine)) * 4)
    print('Generated:', destination)
    print('Generated integer table:', integer_destination)

if __name__ == '__main__':
    main()
